// Bundles the score engine (../score/engine/main.ts: the web app's score code behind a message
// interface) into one self-contained HTML page and writes it as a string module the app loads into
// a WebView. Runs before `expo start` (see package.json); the output is generated, not committed.
import { build } from '../../node_modules/esbuild/lib/main.js';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
const out = resolve(here, '..', 'src', 'score', 'engineHtml.generated.ts');

const result = await build({
  entryPoints: [resolve(repoRoot, 'score', 'engine', 'main.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['es2020', 'safari15'],
  minify: true,
  write: false,
  logLevel: 'warning',
  nodePaths: [resolve(repoRoot, 'node_modules')],
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const html = `<!doctype html>
<html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1">
<style>
  html, body { margin: 0; padding: 0; background: #FAF7F0; -webkit-user-select: none; user-select: none; -webkit-tap-highlight-color: transparent; }
  #wrap { position: relative; padding: 8px 4px 40px; }
  #score { position: relative; }
  #overlay { position: absolute; left: 4px; top: 8px; right: 4px; bottom: 40px; pointer-events: none; z-index: 2; }
</style></head>
<body><div id="wrap"><div id="overlay"></div><div id="score"></div></div>
<script>${js}</script></body></html>`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// Generated by scripts/build-score-engine.mjs -- do not edit.\n/* eslint-disable */\nexport const SCORE_ENGINE_HTML = ${JSON.stringify(html)};\n`);
console.log(`score engine: ${(html.length / 1024).toFixed(0)} KB -> ${out}`);
